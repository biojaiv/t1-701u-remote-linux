#!/usr/bin/env python3
"""Generates tablet/font_aa.h: anti-aliased glyphs for the status page.

Two faces, rendered once from DejaVu fonts (free licence):
  clock  DejaVu Sans ExtraLight, 168 px: digits, colon, hyphen
  text   DejaVu Sans, 28 px: printable ASCII, German umlauts and a few signs
Each glyph is cut to its ink box and stored with 4-bit coverage (two pixels
per byte, high nibble first, every glyph starts on a byte). The generated
file is committed; run this again only to change fonts or sizes.

Usage: genfont_aa.py > tablet/font_aa.h
"""
from PIL import Image, ImageDraw, ImageFont

DIR = "/usr/share/fonts/truetype/dejavu/"
FACES = (
    ("clock", DIR + "DejaVuSans-ExtraLight.ttf", 168, "0123456789:-"),
    ("text", DIR + "DejaVuSans.ttf", 28,
     "".join(chr(c) for c in range(32, 127)) + "äöüÄÖÜß°–·•⚡"),
)


def glyph(font, char, size):
    pad = size
    img = Image.new("L", (size * 3, size * 3), 0)
    baseline = pad + size
    ImageDraw.Draw(img).text((pad, baseline), char, font=font, fill=255, anchor="ls")
    box = img.getbbox()
    advance = round(font.getlength(char))
    if box is None:   # space
        return dict(x=0, y=0, w=0, h=0, adv=advance, px=[])
    x0, y0, x1, y1 = box
    px = [round(img.getpixel((x, y)) * 15 / 255) for y in range(y0, y1) for x in range(x0, x1)]
    return dict(x=x0 - pad, y=y0 - baseline, w=x1 - x0, h=y1 - y0, adv=advance, px=px)


def main():
    print("/* Generated by scripts/genfont_aa.py from DejaVu fonts. Do not edit. */")
    print("/* 4-bit coverage, two pixels per byte, high nibble first. */")
    data = bytearray()
    for name, path, size, chars in FACES:
        font = ImageFont.truetype(path, size)
        ascent, descent = font.getmetrics()
        entries = []
        for char in chars:
            g = glyph(font, char, size)
            offset = len(data)
            for row in range(g["h"]):
                line = g["px"][row * g["w"]:(row + 1) * g["w"]]
                if len(line) % 2:
                    line = line + [0]
                for i in range(0, len(line), 2):
                    data.append(line[i] << 4 | line[i + 1])
            entries.append((ord(char), g["x"], g["y"], g["w"], g["h"], g["adv"], offset))
        print(f"static const struct glyph glyphs_{name}[{len(entries)}] = {{")
        for cp, x, y, w, h, adv, off in entries:
            print(f"    {{ 0x{cp:04x}, {x}, {y}, {w}, {h}, {adv}, {off} }},")
        print("};")
        print(f"#define FACE_{name.upper()}_ASCENT {ascent}")
        print(f"#define FACE_{name.upper()}_COUNT {len(entries)}")
    print(f"static const uint8_t glyph_pixels[{len(data)}] = {{")
    for i in range(0, len(data), 24):
        print("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    print("};")


if __name__ == "__main__":
    main()
